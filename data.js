export const TOPIC_BY_ID = Object.fromEntries(TOPICS.map((t) => [t.id, t]));

export function topicStatus(topic, done) {
  if (done[topic.id]) return 'done';
  return topic.needs.every((n) => done[n]) ? 'open' : 'locked';
}
